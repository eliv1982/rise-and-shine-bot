@pytest.mark.parametrize('mutation', ['key', 'eligible', 'basis', 'span', 'classification', 'negative', 'missing', 'injected'])
def test_semantic_forgery_cannot_gain_authority_with_valid_refs(mutation):
    source = vi.interpret_visual_intent('Show a mug; No people')
    facts = source.facts
    if mutation == 'key':
        forged = replace(source, facts=(replace(facts[0], key='table'), *facts[1:]))
    elif mutation == 'basis':
        forged = replace(source, facts=(replace(facts[0], basis=vi.FactBasis.CUSTOM_NOMINAL), *facts[1:]))
    elif mutation == 'span':
        forged = replace(source, facts=(replace(facts[0], span=sg.Span(8, 10)), *facts[1:]))
    elif mutation in {'eligible', 'classification'}:
        forged = replace(source, facts=(replace(facts[0], eligible=False), *facts[1:]),
                         classifications=(replace(source.classifications[0], request_class='nonvisual'), source.classifications[1]))
    elif mutation == 'negative':
        forged = replace(source, negatives=(replace(source.negatives[0], classification='nonvisual'),))
    elif mutation == 'missing':
        forged = replace(source, facts=(facts[1],), classifications=(
            replace(source.classifications[0], request_class='nonvisual', fact_indices=()),
            replace(source.classifications[1], fact_indices=(0,))),
            negatives=(replace(source.negatives[0], fact_indices=(0,)),))
    else:
        forged = replace(source, facts=(*facts, facts[0]), classifications=(
            replace(source.classifications[0], fact_indices=(0, 2)), source.classifications[1]))
    with pytest.raises(VisualSafetyFailure, match='INVALID_EVIDENCE'):
        sg.resolve_visual_intent(forged)
    original = resolve('Show a mug; No people')
    rehashed = replace(original, interpretation=forged)
    rehashed = replace(rehashed, resolution_digest=sg._digest(rehashed))
    with pytest.raises(VisualSafetyFailure, match='INVALID_EVIDENCE'):
        sg.check_interpretation(rehashed)


