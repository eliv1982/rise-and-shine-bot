def resolve(text='Show a table; No mugs', *, style='auto', mode='illustration', notes=None):
    return sg.resolve_visual_intent(vi.interpret_visual_intent(text, style=style, custom_style_description=notes),
                                    requested_style=style, requested_mode=mode)


def gate(text='Show a table; No mugs', *, registry=None, policy=None, style='auto', mode='illustration', notes=None,
         adapter='fake-adapter', model='fake-model', size='fake-size'):
    if registry is None:
        registry, default_policy = synthetic_registry(style=style, mode=mode)
    else:
        _, default_policy = synthetic_registry()
    return sg.create_synthetic_gate(resolve(text, style=style, mode=mode, notes=notes), registry, policy or default_policy,
        context_id='test-context', adapter_id=adapter, model=model, size=size)


